"""Embeddings: honest jsonb ↔ pgvector reconciliation (settings-flag gated).

History: 0006 added `embedding` as JSONField, while models.py has always
declared VectorField whenever the *python lib* imported — a latent
model/migration divergence (autogenerated changes would one day try to cast
jsonb→vector with no USING clause). The pgvector server extension is a
separate install (postgresql-18-pgvector locally; built into Supabase), so
the column type a database can actually host is decided here by settings
rather than at model import.

- PGVECTOR_ENABLED=False: state stays JSONField (no DB change).
- PGVECTOR_ENABLED=True: CREATE EXTENSION vector, cast both columns
  jsonb→vector(384) — the stored data is plain float arrays either way — and
  add HNSW cosine indexes (usable from MAX_CANDIDATES-scale pools upward).

Flipping the flag later (e.g. on Supabase) turns this same migration into
the correct upgrade on that database: CastToVector handles fresh databases,
and `_upgrade` is a no-op on ones already vectorized.
"""

from django.conf import settings
from django.db import migrations, models

try:
    from pgvector.django import VectorField as _VectorField
except Exception:  # pragma: no cover - lib absence matches models.py fallback
    _VectorField = None

_EMBEDDING_TABLES = ("catalog_movie", "catalog_show")


def _column_type(cursor, table):
    cursor.execute(
        "SELECT data_type FROM information_schema.columns "
        "WHERE table_name = %s AND column_name = 'embedding'",
        [table],
    )
    row = cursor.fetchone()
    return row[0] if row else None


def _backend_ready(cursor):
    """Extension files present on the server (Superuser rights alone don't
    help when the package is missing — probe, don't assume)."""
    cursor.execute(
        "SELECT EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'vector')"
    )
    return cursor.fetchone()[0]


def _upgrade(apps, schema_editor):
    if schema_editor.connection.vendor != "postgresql":
        return
    with schema_editor.connection.cursor() as cursor:
        if all(_column_type(cursor, t) == "user-defined" for t in _EMBEDDING_TABLES):
            return  # already vectorized
        if not getattr(settings, "PGVECTOR_ENABLED", False):
            return  # flag off: this database keeps its jsonb columns
        if not _backend_ready(cursor):
            raise RuntimeError(
                "PGVECTOR_ENABLED=1 but the pgvector server extension is not "
                "installed. Install it first (apt install postgresql-18-pgvector, "
                "or use a host with pgvector like Supabase), then rerun migrate."
            )
        cursor.execute("CREATE EXTENSION IF NOT EXISTS vector")
        for table in _EMBEDDING_TABLES:
            cursor.execute(
                f"ALTER TABLE {table} ALTER COLUMN embedding "
                f"TYPE vector(384) USING embedding::text::vector(384)"
            )
            cursor.execute(
                f"CREATE INDEX IF NOT EXISTS {table}_embedding_hnsw "
                f"ON {table} USING hnsw (embedding vector_cosine_ops)"
            )


def _downgrade(apps, schema_editor):
    if schema_editor.connection.vendor != "postgresql":
        return
    with schema_editor.connection.cursor() as cursor:
        vector_tables = [
            t for t in _EMBEDDING_TABLES if _column_type(cursor, t) == "user-defined"
        ]
        if not vector_tables:
            return  # nothing was vectorized on this database
        if not _backend_ready(cursor):
            raise RuntimeError(
                "pgvector columns exist but the server extension is gone; "
                "reinstall it before downgrading."
            )
        for table in vector_tables:
            cursor.execute(f"DROP INDEX IF EXISTS {table}_embedding_hnsw")
            # vector's text form '[1.5,2.5,...]' parses as a JSON array
            cursor.execute(
                f"ALTER TABLE {table} ALTER COLUMN embedding TYPE jsonb "
                f"USING embedding::text::jsonb"
            )


class Migration(migrations.Migration):
    dependencies = [
        ("catalog", "0007_movie_cast_movie_writers_show_cast_and_more"),
    ]

    operations = [
        migrations.SeparateDatabaseAndState(
            database_operations=[
                migrations.RunPython(_upgrade, _downgrade),
            ],
            state_operations=(
                [
                    migrations.AlterField(
                        model_name="movie",
                        name="embedding",
                        field=_VectorField(dimensions=384, null=True, blank=True),
                    ),
                    migrations.AlterField(
                        model_name="show",
                        name="embedding",
                        field=_VectorField(dimensions=384, null=True, blank=True),
                    ),
                ]
                if _VectorField is not None and settings.PGVECTOR_ENABLED
                else [
                    migrations.AlterField(
                        model_name="movie",
                        name="embedding",
                        field=models.JSONField(null=True, blank=True),
                    ),
                    migrations.AlterField(
                        model_name="show",
                        name="embedding",
                        field=models.JSONField(null=True, blank=True),
                    ),
                ]
            ),
        ),
    ]
